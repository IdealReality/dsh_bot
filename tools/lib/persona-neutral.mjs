/** 人格正文是否可用（与 lib/agent-prompt.readPersonaChecked 同判据，保持两条路径一致）。 */
export function personaUsable(text) {
  const t = String(text || '').trim()
  if (t.length < 200) return false
  // 2026-11-07 实测：人格里写"不要用『作为一个 AI』去填"会被判据误伤成自我否认。
  // 先把引号里的内容剥掉再判（引号内是引用/反面例子，不是她的自我陈述）。
  const body = t.replace(/[「『“"'‘][^」』”"'’]{0,40}[」』”"'’]/g, '')
  const DENIAL = [
    /作为(一个)?\s*(AI|人工智能|语言模型|大模型|助手)/,
    /我(只)?是一个\s*(AI|人工智能|语言模型|大模型|智能助手|助手)/,
    /我没有(记忆|情感|感情|意识|身体)/,
  ]
  return !DENIAL.some((re) => re.test(body))
}

